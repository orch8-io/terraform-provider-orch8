// NewSequenceResource manages one immutable sequence version.
func NewSequenceResource() resource.Resource { return &sequenceResource{} }

type sequenceResource struct{ base }

type sequenceModel struct {
	ID         types.String         `tfsdk:"id"`
	TenantID   types.String         `tfsdk:"tenant_id"`
	Namespace  types.String         `tfsdk:"namespace"`
	Name       types.String         `tfsdk:"name"`
	Version    types.Int64          `tfsdk:"version"`
	Definition jsontypes.Normalized `tfsdk:"definition"`
	Status     types.String         `tfsdk:"status"`
	Deprecated types.Bool           `tfsdk:"deprecated"`
	CreatedAt  types.String         `tfsdk:"created_at"`
	Warnings   types.List           `tfsdk:"warnings"`
}

// Keys owned by resource attributes or assigned by the provider; they may
// appear in `definition` only when they agree with the attributes.
var sequenceIdentityKeys = []string{"id", "tenant_id", "namespace", "name", "version", "created_at"}

func (r *sequenceResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_sequence"
}

