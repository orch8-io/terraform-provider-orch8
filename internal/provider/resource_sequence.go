// buildSequenceBody merges the definition document with identity attributes.
func buildSequenceBody(m *sequenceModel, tenant, id, createdAt string) (map[string]any, diag.Diagnostics) {
	var diags diag.Diagnostics
	body := map[string]any{}
	if err := json.Unmarshal([]byte(m.Definition.ValueString()), &body); err != nil {
		diags.AddAttributeError(path.Root("definition"), "Invalid definition", "definition must be a JSON object: "+err.Error())
		return nil, diags
	}
	if _, ok := body["blocks"]; !ok {
		diags.AddAttributeError(path.Root("definition"), "Invalid definition", "definition must contain a `blocks` array")
		return nil, diags
	}
	want := map[string]any{
		"tenant_id": tenant,
		"namespace": m.Namespace.ValueString(),
		"name":      m.Name.ValueString(),
		"version":   float64(m.Version.ValueInt64()),
	}
	for k, v := range want {
		if got, ok := body[k]; ok && fmt.Sprint(got) != fmt.Sprint(v) {
			diags.AddAttributeError(path.Root("definition"), "Conflicting definition",
				fmt.Sprintf("definition.%s = %v conflicts with attribute %s = %v; remove it from definition or make them match", k, got, k, v))
		}
	}
	if diags.HasError() {
		return nil, diags
	}
	for k, v := range want {
		body[k] = v
	}
	body["version"] = m.Version.ValueInt64()
	body["id"] = id
	body["created_at"] = createdAt
	return body, diags
}

type sequenceWire struct {
	ID         string `json:"id"`
	TenantID   string `json:"tenant_id"`
	Namespace  string `json:"namespace"`
	Name       string `json:"name"`
	Version    int64  `json:"version"`
	Status     string `json:"status"`
	Deprecated bool   `json:"deprecated"`
	CreatedAt  string `json:"created_at"`
}

func (r *sequenceResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan sequenceModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}
	tenant := r.tenantFor(plan.TenantID)
	if !requireTenant(tenant, &resp.Diagnostics) {
		return
	}
	id, err := uuid.NewV7()
	if err != nil {
		resp.Diagnostics.AddError("UUID generation failed", err.Error())
		return
	}
	body, diags := buildSequenceBody(&plan, tenant, id.String(), time.Now().UTC().Format(time.RFC3339Nano))
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}
	var created struct {
		ID       string   `json:"id"`
		Warnings []string `json:"warnings"`
	}
	if err := r.client.Do(ctx, "POST", "/sequences", nil, body, &created); err != nil {
		addAPIError(&resp.Diagnostics, "create sequence", err)
		return
	}
	if created.ID == "" {
		created.ID = id.String()
	}
	plan.ID = types.StringValue(created.ID)
	plan.TenantID = types.StringValue(tenant)
	warnings, d := types.ListValueFrom(ctx, types.StringType, nonNilStrings(created.Warnings))
	resp.Diagnostics.Append(d...)
	plan.Warnings = warnings
	for _, w := range created.Warnings {
		resp.Diagnostics.AddWarning("Orch8 sequence warning", w)
	}
	found := r.read(ctx, &plan, &resp.Diagnostics)
	if !found && !resp.Diagnostics.HasError() {
		resp.Diagnostics.AddError("Sequence vanished", "sequence was created but could not be read back")
	}
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func nonNilStrings(s []string) []string {
	if s == nil {
		return []string{}
	}
	return s
}

// read refreshes server-owned attributes. The definition itself is not
// rewritten from the server (the engine re-serializes blocks with defaults,
// which would cause spurious replacements); drift in identity fields and
// deletion are detected.
func (r *sequenceResource) read(ctx context.Context, m *sequenceModel, diags *diag.Diagnostics) bool {
	var s sequenceWire
	var raw json.RawMessage
	if err := r.client.Do(ctx, "GET", "/sequences/"+m.ID.ValueString(), nil, nil, &raw); err != nil {
		if isNotFound(err) {
			return false
		}
		addAPIError(diags, "read sequence", err)
		return false
	}
	if err := json.Unmarshal(raw, &s); err != nil {
		diags.AddError("Decode error", err.Error())
		return false
	}
	m.TenantID = types.StringValue(s.TenantID)
	m.Namespace = types.StringValue(s.Namespace)
	m.Name = types.StringValue(s.Name)
	m.Version = types.Int64Value(s.Version)
	m.Status = types.StringValue(s.Status)
	m.Deprecated = types.BoolValue(s.Deprecated)
	m.CreatedAt = types.StringValue(s.CreatedAt)
	if m.Definition.IsNull() || m.Definition.IsUnknown() {
		// Import: seed definition from the server's body without identity keys.
		m.Definition = jsontypes.NewNormalizedValue(stripKeys(raw, append(sequenceIdentityKeys, "deprecated")))
	}
	if m.Warnings.IsNull() || m.Warnings.IsUnknown() {
		m.Warnings = types.ListValueMust(types.StringType, nil)
	}
	return true
}

func stripKeys(raw json.RawMessage, keys []string) string {
	var obj map[string]json.RawMessage
	if json.Unmarshal(raw, &obj) != nil {
		return string(raw)
	}
	for _, k := range keys {
		delete(obj, k)
	}
	out, _ := json.Marshal(obj)
	return string(out)
}

func (r *sequenceResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var st sequenceModel
	resp.Diagnostics.Append(req.State.Get(ctx, &st)...)
	if resp.Diagnostics.HasError() {
		return
	}
	if !r.read(ctx, &st, &resp.Diagnostics) {
		if !resp.Diagnostics.HasError() {
			resp.State.RemoveResource(ctx)
		}
		return
	}
	resp.Diagnostics.Append(resp.State.Set(ctx, &st)...)
}

func (r *sequenceResource) Update(_ context.Context, _ resource.UpdateRequest, resp *resource.UpdateResponse) {
	resp.Diagnostics.AddError("Update not supported", "orch8_sequence versions are immutable; every change forces replacement.")
}

func (r *sequenceResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var st sequenceModel
	resp.Diagnostics.Append(req.State.Get(ctx, &st)...)
	if resp.Diagnostics.HasError() {
		return
	}
	if err := r.client.Do(ctx, "DELETE", "/sequences/"+st.ID.ValueString(), nil, nil, nil); err != nil && !isNotFound(err) {
		addAPIError(&resp.Diagnostics, "delete sequence", err)
	}
}

func (r *sequenceResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	resource.ImportStatePassthroughID(ctx, path.Root("id"), req, resp)
}
